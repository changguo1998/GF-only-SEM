"""Run the approved source-depth sweep sequentially, retaining compact results."""

import csv
import math
import os
import shutil
import subprocess
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASE = ROOT / "examples/halfspace-50x50x25"
RESULTS = CASE / "depth_sweep"
RESULTS.mkdir(exist_ok=True)
PYTHON = ROOT / ".venv/bin/python"
PREPROCESS = ROOT / "bin-cpp-halfspace/gf_preprocess"


def run(command, log_path, environment):
    started = time.monotonic()
    with log_path.open("w") as log:
        result = subprocess.run(
            command, cwd=CASE, env=environment, stdout=log, stderr=subprocess.STDOUT
        )
    print(
        f"{log_path.name}: exit={result.returncode}, elapsed={time.monotonic() - started:.1f}s",
        flush=True,
    )
    return result.returncode


for depth_m in (500, 200, 100, 50, 10):
    destination = RESULTS / f"depth_{depth_m:04d}m"
    if (destination / "metrics.csv").exists() and (destination / "greenfun").is_dir():
        print(f"SKIP completed depth={depth_m}m", flush=True)
        continue
    destination.mkdir(exist_ok=True)
    environment = dict(
        os.environ,
        GF_SOURCE_DEPTH_M=str(depth_m),
        GF_REUSE_PREPROCESSED="1",
        PYTHONPATH=str(ROOT),
        OMP_NUM_THREADS="8",
    )
    print(f"START depth={depth_m}m", flush=True)
    started = time.monotonic()
    assert run([str(PYTHON), "mesh_gen.py"], destination / "mesh.log", environment) == 0
    assert (
        run(
            [
                str(PREPROCESS),
                "run",
                "model.h5",
                "--N",
                "4",
                "--cfl-safety",
                "0.5",
                "--nx",
                "50",
                "--ny",
                "50",
                "--pml-xmin",
                "5",
                "--pml-xmax",
                "5",
                "--pml-ymin",
                "5",
                "--pml-ymax",
                "5",
                "--pml-zmax",
                "5",
                "--n-ranks",
                "16",
            ],
            destination / "preprocess.log",
            environment,
        )
        == 0
    )
    comparison = CASE / "log/lamb_distance_depth.csv"
    if comparison.exists():
        comparison.unlink()
    returncode = run(["bash", "run.sh"], destination / "pipeline.log", environment)
    assert returncode in (0, 1) and comparison.exists(), "Pipeline failed before comparison"
    with comparison.open() as stream:
        rows = list(csv.DictReader(stream))
    assert len(rows) == 5
    for row in rows:
        assert all(
            math.isfinite(float(row[key]))
            for key in ("correlation", "scale", "fitted_relative_l2")
        )
        row["source_depth_m"] = depth_m
        row["passed"] = (
            float(row["correlation"]) >= 0.95
            and 0.8 <= float(row["scale"]) <= 1.2
            and float(row["fitted_relative_l2"]) <= 0.30
        )
    with (destination / "metrics.csv").open("w") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    shutil.copy2(CASE / "config.h5", destination / "config.h5")
    shutil.move(str(CASE / "greenfun"), str(destination / "greenfun"))
    # Remove only wavefields generated by this completed run, after retaining results.
    shutil.rmtree(CASE / "wavefields")
    print(
        f"DONE depth={depth_m}m elapsed={time.monotonic() - started:.1f}s metrics={rows}",
        flush=True,
    )

print("SWEEP COMPLETE", flush=True)
